export async function analyzePhishing(emailContent: string, senderInput?: string, subjectInput?: string) {
  // Defensive email structural and content parser
  const senderMatch = senderInput || emailContent.match(/from:\s*([^\r\n]+)/i)?.[1]?.trim() || "Unknown Sender";
  const subjectMatch = subjectInput || emailContent.match(/subject:\s*([^\r\n]+)/i)?.[1]?.trim() || "No Subject";
  
  // Extract URLs safely using regex
  const urlRegex = /(https?:\/\/[^\s<>"'\)]+)/gi;
  const extractedUrls: string[] = Array.from(new Set(emailContent.match(urlRegex) || []));

  // Heuristic indicators
  const urgencyKeywords = ["urgent", "immediate action required", "account suspended", "24 hours", "suspended immediately", "verify your account", "payroll", "tax refund", "wire transfer", "terminate your access"];
  const credentialKeywords = ["login", "password", "sign in", "credentials", "authenticate", "verify direct deposit", "sso", "security code", "mfa token", "update payment"];
  
  const foundUrgency = urgencyKeywords.filter((k) => emailContent.toLowerCase().includes(k));
  const foundCredential = credentialKeywords.filter((k) => emailContent.toLowerCase().includes(k));

  // Domain mismatch heuristic
  let domainMismatch = false;
  let senderDomain = "";
  if (senderMatch.includes("@")) {
    senderDomain = senderMatch.split("@")[1].replace(/[<>]/g, "").trim().toLowerCase();
  }
  
  for (const url of extractedUrls) {
    try {
      const parsed = new URL(url);
      if (senderDomain && !parsed.hostname.endsWith(senderDomain) && !senderDomain.endsWith(parsed.hostname)) {
        domainMismatch = true;
      }
    } catch {
      // ignore parse err
    }
  }

  // Calculate heuristic risk score
  let riskScore = 15;
  const reasons: string[] = [];

  if (foundUrgency.length > 0) {
    riskScore += 25;
    reasons.push(`High psychological urgency markers detected: "${foundUrgency.slice(0, 3).join('", "')}".`);
  }
  if (foundCredential.length > 0) {
    riskScore += 30;
    reasons.push(`Direct credential harvesting keywords detected: "${foundCredential.slice(0, 3).join('", "')}".`);
  }
  if (domainMismatch) {
    riskScore += 20;
    reasons.push(`Domain Mismatch: Inbound sender claim (${senderDomain || "company"}) does not match embedded URL destination host.`);
  }
  if (extractedUrls.some((u) => u.includes(".top") || u.includes(".cc") || u.includes(".xyz") || u.includes(".duckdns") || u.includes("bit.ly"))) {
    riskScore += 15;
    reasons.push("Embedded link utilizes suspicious or high-abuse Top-Level Domain (TLD) / shortener.");
  }
  if (extractedUrls.length === 0 && (foundUrgency.length > 0 || foundCredential.length > 0)) {
    riskScore += 10;
    reasons.push("Potential BEC (Business Email Compromise) / gift card or wire fraud without links.");
  }

  riskScore = Math.min(Math.max(riskScore, 5), 98);
  const classification = riskScore >= 75 ? "Phishing (High Confidence)" : riskScore >= 45 ? "Suspicious / Potential Phish" : "Low Risk / Clean";

  // Try Gemini for enhanced explanation if key available
  let geminiAnalysis: string | null = null;
  if (apiKey) {
    try {
      const prompt = `Analyze this simulated email defensively for a SOC training platform:
Sender: ${senderMatch}
Subject: ${subjectMatch}
Content:
"""
${emailContent.slice(0, 1500)}
"""

Provide a concise 3-paragraph defensive analysis:
1. Threat classification and psychological trigger techniques used (scarcity, authority, urgency).
2. Indicator extraction and domain correlation risks.
3. Recommended SOC containment actions (e.g. purge from mailboxes, block sender IP, reset user tokens).`;

      const res = await ai.models.generateContent({
        model: "gemini-3.8-flash",
        contents: prompt,
        config: {
          systemInstruction: "You are an automated email security gateway (SEG) defensive analyst analyzer.",
          temperature: 0.2,
        },
      });
      geminiAnalysis = res.text || null;
    } catch (e: any) {
      console.warn("Gemini phishing analysis error:", e?.message);
    }
  }

  return {
    sender: senderMatch,
    subject: subjectMatch,
    extractedUrls,
    urgencyMarkers: foundUrgency,
    credentialRequests: foundCredential,
    domainMismatch,
    riskScore,
    classification,
    reasons,
    aiAnalysis: geminiAnalysis,
    recommendedInvestigation: [
      "Quarantine message across all tenant Microsoft 365 / Google Workspace inboxes.",
      "Check gateway logs for other recipients of the same sender/subject combination.",
      "Submit embedded URLs to defensive sandbox simulation.",
      "If user interacted with link, initiate credential reset and review sign-in logs.",
    ],
  };
}

export function analyzeUrlStructure(rawUrl: string) {
  // Pure structural URL analyzer - DOES NOT actively connect or scan
  let parsed: URL;
  try {
    const formatted = rawUrl.startsWith("http://") || rawUrl.startsWith("https://") ? rawUrl : `http://${rawUrl}`;
    parsed = new URL(formatted);
  } catch {
    return {
      valid: false,
      error: "Invalid URL format. Please provide a standard URL string.",
      riskScore: 50,
      classification: "Malformed URL",
      checks: [],
      structuralDetails: null,
    };
  }

  const hostname = parsed.hostname;
  const checks: { name: string; status: "safe" | "warning" | "danger"; details: string; points: number }[] = [];
  let score = 10;

  // 1. Protocol check
  if (parsed.protocol === "https:") {
    checks.push({
      name: "Transport Security (HTTPS)",
      status: "safe",
      details: "URL specifies HTTPS protocol.",
      points: -5,
    });
  } else {
    checks.push({
      name: "Transport Security (HTTP)",
      status: "warning",
      details: "URL uses unencrypted plain HTTP transport.",
      points: 15,
    });
    score += 15;
  }

  // 2. IP Address as host check
  const ipV4Regex = /^(\d{1,3}\.){3}\d{1,3}$/;
  if (ipV4Regex.test(hostname)) {
    checks.push({
      name: "IP-Based Hostname",
      status: "danger",
      details: "Hostname is a raw IP address rather than a registered domain name (common evasion tactic).",
      points: 30,
    });
    score += 30;
  } else {
    checks.push({
      name: "Domain Hostname",
      status: "safe",
      details: "Uses domain name system rather than raw IP.",
      points: 0,
    });
  }

  // 3. Length checks
  if (rawUrl.length > 90) {
    checks.push({
      name: "Excessive URL Length",
      status: "warning",
      details: `URL length is ${rawUrl.length} characters (typical phishing lures use excessive length to obscure the host).`,
      points: 15,
    });
    score += 15;
  } else {
    checks.push({
      name: "URL Length",
      status: "safe",
      details: `Normal length (${rawUrl.length} characters).`,
      points: 0,
    });
  }

  // 4. Unusual / high-risk TLD
  const suspiciousTlds = [".top", ".xyz", ".cc", ".tk", ".ml", ".ga", ".cf", ".gq", ".buzz", ".work", ".click", ".fit", ".country"];
  const matchesSusTld = suspiciousTlds.some((tld) => hostname.endsWith(tld));
  if (matchesSusTld) {
    checks.push({
      name: "High-Abuse Top-Level Domain (TLD)",
      status: "danger",
      details: `Domain uses a TLD with statistically elevated threat reputation in synthetic security feeds.`,
      points: 25,
    });
    score += 25;
  } else {
    checks.push({
      name: "Standard Top-Level Domain",
      status: "safe",
      details: "Domain uses standard corporate or country-code TLD.",
      points: 0,
    });
  }

  // 5. Excessive subdomains
  const subdomains = hostname.split(".").filter(Boolean);
  if (subdomains.length > 3) {
    checks.push({
      name: "Excessive Subdomains",
      status: "warning",
      details: `Domain contains ${subdomains.length} labels (subdomain nesting often used to disguise brand names).`,
      points: 18,
    });
    score += 18;
  }

  // 6. Suspicious characters / Punycode / @ symbol
  if (rawUrl.includes("@")) {
    checks.push({
      name: "Embedded Credential / Userinfo Symbol (@)",
      status: "danger",
      details: "URL contains '@' character used in browser URL spoofing to mask destination host.",
      points: 35,
    });
    score += 35;
  }

  if (hostname.startsWith("xn--")) {
    checks.push({
      name: "Internationalized Domain / Punycode",
      status: "warning",
      details: "Punycode domain detected (potential homograph attack simulating standard Latin characters).",
      points: 20,
    });
    score += 20;
  }

  // 7. Suspicious path patterns
  const pathLower = parsed.pathname.toLowerCase();
  const susPaths = ["/login", "/auth", "/signin", "/verify", "/account", "/wallet", "/secure", "/update", "/banking", "/webscr"];
  const matchedPath = susPaths.find((p) => pathLower.includes(p));
  if (matchedPath) {
    checks.push({
      name: "High-Risk Path Keyword",
      status: "warning",
      details: `Path contains sensitive credential keyword: "${matchedPath}".`,
      points: 15,
    });
    score += 15;
  }

  score = Math.min(Math.max(score, 5), 99);
  const classification = score >= 70 ? "High Risk (Malicious Pattern)" : score >= 40 ? "Suspicious Structure" : "Low Risk / Clean Structure";

  return {
    valid: true,
    url: rawUrl,
    riskScore: score,
    classification,
    structuralDetails: {
      protocol: parsed.protocol,
      hostname: parsed.hostname,
      port: parsed.port || (parsed.protocol === "https:" ? "443" : "80"),
      pathname: parsed.pathname,
      search: parsed.search,
      hash: parsed.hash,
      length: rawUrl.length,
    },
    checks,
    defensiveGuidance: [
      "No active connection or scanning was initiated against this host.",
      "Check internal proxy logs to determine if any internal workstations requested this domain.",
      "Correlate domain against DNS Response Policy Zone (RPZ) feeds.",
      "If classified as high risk, configure perimeter perimeter DNS sinkhole.",
    ],
  };
}
