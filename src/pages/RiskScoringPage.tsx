import React, { useState, useEffect } from "react";
import {
  Scale,
  ShieldAlert,
  AlertTriangle,
  Info,
  CheckCircle2,
  Sliders,
  TrendingUp,
  RefreshCw,
} from "lucide-react";
import { api } from "../services/api";
import { Incident } from "../types";

interface RiskScoringPageProps {
  initialIncidentId?: string;
}

export const RiskScoringPage: React.FC<RiskScoringPageProps> = ({ initialIncidentId }) => {
  const [incidents, setIncidents] = useState<Incident[]>([]);
  const [selectedIncidentId, setSelectedIncidentId] = useState<string>(initialIncidentId || "");
  const [loading, setLoading] = useState(true);

  // Interactive sandbox weights
  const [tiMatch, setTiMatch] = useState(true);
  const [abnormalLogin, setAbnormalLogin] = useState(true);
  const [endpointExecution, setEndpointExecution] = useState(true);
  const [criticalAssetTarget, setCriticalAssetTarget] = useState(true);
  const [wafMitigationActive, setWafMitigationActive] = useState(false);

  useEffect(() => {
    api.getIncidents().then((res) => {
      const list = res.incidents || [];
      setIncidents(list);
      if (!selectedIncidentId && list.length > 0) {
        setSelectedIncidentId(list[0].incidentId);
      }
      setLoading(false);
    }).catch(console.error);
  }, []);

  useEffect(() => {
    if (initialIncidentId) {
      setSelectedIncidentId(initialIncidentId);
    }
  }, [initialIncidentId]);

  const activeIncident = incidents.find((i) => i.incidentId === selectedIncidentId) || incidents[0];

  // Calculate sandbox score
  let simScore = 10;
  if (tiMatch) simScore += 25;
  if (abnormalLogin) simScore += 30;
  if (endpointExecution) simScore += 22;
  if (criticalAssetTarget) simScore += 15;
  if (wafMitigationActive) simScore -= 12;
  simScore = Math.min(Math.max(simScore, 0), 100);

  return (
    <div className="space-y-6">
      {/* Title */}
      <div>
        <h1 className="text-2xl font-bold tracking-tight text-white flex items-center gap-2">
          Explainable Incident Risk Scoring System
        </h1>
        <p className="text-xs text-slate-400 mt-1">
          Algorithmic transparency: deconstructs composite SOC risk scores into deterministic, auditable heuristic factors.
        </p>
      </div>

      {/* Probability Clarification Disclaimer */}
      <div className="bg-slate-950 border border-slate-800 rounded-xl p-4 flex items-start gap-3 text-xs text-slate-300">
        <Info className="w-5 h-5 text-cyan-400 shrink-0 mt-0.5" />
        <div className="space-y-1">
          <span className="font-semibold text-cyan-300">Defensive Methodology Clarification:</span>
          <p className="text-slate-400 leading-relaxed">
            The composite score generated by CyberSentinel X is a calibrated <strong>application-specific priority index</strong> designed to guide defensive SOC analyst triage queues. It is not an absolute mathematical probability of data compromise.
          </p>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* Active Incident Risk Factor Breakdown */}
        <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-sm space-y-4">
          <div className="flex items-center justify-between">
            <h2 className="text-sm font-bold text-white flex items-center gap-2">
              <Scale className="w-4 h-4 text-cyan-400" /> Active Incident Decomposition
            </h2>

            <select
              aria-label="Select incident for risk breakdown"
              value={selectedIncidentId}
              onChange={(e) => setSelectedIncidentId(e.target.value)}
              className="bg-slate-950 border border-slate-700 text-xs rounded px-2.5 py-1 text-slate-200 focus:outline-none focus:border-cyan-500 font-mono cursor-pointer"
            >
              {incidents.map((inc) => (
                <option key={inc.incidentId} value={inc.incidentId}>
                  {inc.incidentId} ({inc.riskScore}/100)
                </option>
              ))}
            </select>
          </div>

          {activeIncident ? (
            <div className="space-y-4 text-xs">
              <div className="bg-slate-950 p-4 rounded-xl border border-slate-800 flex items-center justify-between">
                <div>
                  <div className="text-[10px] uppercase font-bold text-slate-400">Selected Incident</div>
                  <div className="font-bold text-slate-100 text-sm">{activeIncident.incidentId}</div>
                  <div className="text-slate-400 line-clamp-1">{activeIncident.title}</div>
                </div>

                <div className="text-right">
                  <div className="text-[10px] uppercase font-bold text-slate-400">Total Score</div>
                  <div className="font-mono text-3xl font-black text-red-400">
                    {activeIncident.riskScore}
                    <span className="text-xs text-slate-500 font-normal">/100</span>
                  </div>
                </div>
              </div>

              {/* Factors List */}
              <div className="space-y-2">
                <span className="font-bold text-slate-200 block">Correlated Scoring Factors:</span>
                {(activeIncident.riskBreakdown?.factors || [
                  { name: "Threat Intelligence Match", points: 25, reason: "Domain matches synthetic phishing threat feed." },
                  { name: "Abnormal Authentication", points: 30, reason: "Impossible travel velocity anomaly recorded." },
                  { name: "Suspicious PowerShell Execution", points: 22, reason: "Encoded Base64 payload in user space." },
                  { name: "Sensitive Subnet Exposure", points: 15, reason: "Host is in finance production segment." },
                ]).map((f, i) => (
                  <div key={i} className="bg-slate-950/70 p-3 rounded-lg border border-slate-800 space-y-1">
                    <div className="flex items-center justify-between">
                      <span className="font-semibold text-slate-200">{f.name}</span>
                      <span className="font-mono font-bold text-cyan-400">
                        {f.points > 0 ? `+${f.points}` : f.points} pts
                      </span>
                    </div>
                    <p className="text-slate-400 text-[11px]">{f.reason}</p>
                  </div>
                ))}
              </div>

              <div className="p-3 rounded-lg bg-cyan-950/20 border border-cyan-800/40 text-slate-300 text-[11px] leading-relaxed">
                <span className="font-bold text-cyan-400 block mb-0.5">Analyst Explanation:</span>
                {activeIncident.riskBreakdown?.explanation ||
                  "Risk index reflects confirmed multi-stage ingress and anomalous identity telemetry requiring priority analyst containment."}
              </div>
            </div>
          ) : (
            <div className="text-slate-400 text-xs">Loading incident risk breakdown...</div>
          )}
        </div>

        {/* Interactive Heuristic Sandbox Simulator */}
        <div className="bg-slate-900 border border-slate-800 rounded-xl p-5 shadow-sm space-y-4">
          <div className="flex items-center justify-between">
            <h2 className="text-sm font-bold text-white flex items-center gap-2">
              <Sliders className="w-4 h-4 text-cyan-400" /> Interactive Scoring Calibration Sandbox
            </h2>
            <button
              onClick={() => {
                setTiMatch(true);
                setAbnormalLogin(true);
                setEndpointExecution(true);
                setCriticalAssetTarget(true);
                setWafMitigationActive(false);
              }}
              className="text-[11px] text-slate-400 hover:text-slate-200"
            >
              Reset Weights
            </button>
          </div>

          <p className="text-xs text-slate-400">
            Simulate how modifying telemetry correlations and active mitigating controls impacts the composite score:
          </p>

          <div className="space-y-3 text-xs">
            <label className="flex items-center justify-between p-3 rounded-lg bg-slate-950 border border-slate-800 cursor-pointer hover:border-slate-700 transition">
              <div>
                <span className="font-semibold text-slate-200 block">Threat Intelligence Match (+25)</span>
                <span className="text-[11px] text-slate-400">Indicator verified in high-confidence threat feed</span>
              </div>
              <input
                type="checkbox"
                checked={tiMatch}
                onChange={(e) => setTiMatch(e.target.checked)}
                className="w-4 h-4 accent-cyan-500 cursor-pointer"
              />
            </label>

            <label className="flex items-center justify-between p-3 rounded-lg bg-slate-950 border border-slate-800 cursor-pointer hover:border-slate-700 transition">
              <div>
                <span className="font-semibold text-slate-200 block">Abnormal Authentication / Impossible Travel (+30)</span>
                <span className="text-[11px] text-slate-400">Simultaneous sessions across extreme geographical bounds</span>
              </div>
              <input
                type="checkbox"
                checked={abnormalLogin}
                onChange={(e) => setAbnormalLogin(e.target.checked)}
                className="w-4 h-4 accent-cyan-500 cursor-pointer"
              />
            </label>

            <label className="flex items-center justify-between p-3 rounded-lg bg-slate-950 border border-slate-800 cursor-pointer hover:border-slate-700 transition">
              <div>
                <span className="font-semibold text-slate-200 block">High-Privilege Process Injection (+22)</span>
                <span className="text-[11px] text-slate-400">EDR detected shell injection or memory modification</span>
              </div>
              <input
                type="checkbox"
                checked={endpointExecution}
                onChange={(e) => setEndpointExecution(e.target.checked)}
                className="w-4 h-4 accent-cyan-500 cursor-pointer"
              />
            </label>

            <label className="flex items-center justify-between p-3 rounded-lg bg-slate-950 border border-slate-800 cursor-pointer hover:border-slate-700 transition">
              <div>
                <span className="font-semibold text-slate-200 block">Tier-1 Critical Asset In Scope (+15)</span>
                <span className="text-[11px] text-slate-400">Host holds financial or directory infrastructure assets</span>
              </div>
              <input
                type="checkbox"
                checked={criticalAssetTarget}
                onChange={(e) => setCriticalAssetTarget(e.target.checked)}
                className="w-4 h-4 accent-cyan-500 cursor-pointer"
              />
            </label>

            <label className="flex items-center justify-between p-3 rounded-lg bg-slate-950 border border-slate-800 cursor-pointer hover:border-slate-700 transition">
              <div>
                <span className="font-semibold text-emerald-400 block">Active WAF / Compensating Control (-12)</span>
                <span className="text-[11px] text-slate-400">Inline firewall blocked payload delivery in transit</span>
              </div>
              <input
                type="checkbox"
                checked={wafMitigationActive}
                onChange={(e) => setWafMitigationActive(e.target.checked)}
                className="w-4 h-4 accent-cyan-500 cursor-pointer"
              />
            </label>

            {/* Simulated Total */}
            <div className="bg-slate-950 p-4 rounded-xl border border-cyan-900/60 flex items-center justify-between mt-4">
              <div>
                <div className="text-[10px] uppercase font-bold text-slate-400">Simulated Composite Score</div>
                <div className={`text-base font-bold ${simScore >= 75 ? "text-red-400" : simScore >= 50 ? "text-amber-400" : "text-emerald-400"}`}>
                  {simScore >= 75 ? "Tier 1 - Critical Containment" : simScore >= 50 ? "Tier 2 - Elevated Monitoring" : "Tier 3 - Standard Telemetry"}
                </div>
              </div>

              <div className="font-mono text-3xl font-black text-cyan-400">
                {simScore}
                <span className="text-xs text-slate-500 font-normal">/100</span>
              </div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
